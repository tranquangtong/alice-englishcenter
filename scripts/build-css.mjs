import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = fileURLToPath(new URL('../', import.meta.url));

// Keep strings, escapes, data URLs and arithmetic intact. In particular, never
// remove descendant-selector whitespace before ':' or spaces around calc +/-.
export function minifyCSS(source) {
  let output = '', pendingSpace = false;
  const punctuation = '{};,>';
  for (let i = 0; i < source.length; i++) {
    const char = source[i];
    if (char === '/' && source[i + 1] === '*') {
      const end = source.indexOf('*/', i + 2);
      if (end < 0) throw new Error('Unclosed CSS comment');
      // A comment can separate tokens without being a descendant combinator.
      if (!pendingSpace && /[\w-]/.test(output.at(-1) || '') && /[\w-]/.test(source[end + 2] || '')) output += '/**/';
      i = end + 1;
      continue;
    }
    if (/\s/.test(char)) { pendingSpace = true; continue; }
    if (pendingSpace && output && !punctuation.includes(output.at(-1)) && output.at(-1) !== ':' && !punctuation.includes(char)) output += ' ';
    pendingSpace = false;
    if (char === '}' && output.endsWith(';')) output = output.slice(0, -1);
    // URL tokens may contain comment-looking text; preserve their payload too.
    if ((char === 'u' || char === 'U') && /^url\(/i.test(source.slice(i)) && !/[\w-]/.test(source[i - 1] || '')) {
      const start = i;
      let quote = '', closed = false;
      for (i += 4; i < source.length; i++) {
        if (source[i] === '\\') { i++; continue; }
        if (quote) { if (source[i] === quote) quote = ''; }
        else if (source[i] === '"' || source[i] === "'") quote = source[i];
        else if (source[i] === ')') { closed = true; break; }
      }
      if (!closed) throw new Error('Unclosed CSS URL');
      output += source.slice(start, i + 1);
      continue;
    }
    output += char;
    if (char === '\\') {
      if (++i >= source.length) throw new Error('Trailing CSS escape');
      if (/[\da-f]/i.test(source[i])) {
        let digits = 0;
        while (digits < 6 && /[\da-f]/i.test(source[i] || '')) { output += source[i++]; digits++; }
        if (/\s/.test(source[i] || '')) {
          output += source[i++];
          if (source[i - 1] === '\r' && source[i] === '\n') output += source[i++];
        }
        i--;
      } else output += source[i];
    } else if (char === '"' || char === "'") {
      const quote = char;
      let closed = false;
      while (++i < source.length) {
        output += source[i];
        if (source[i] === '\\') { output += source[++i] || ''; continue; }
        if (source[i] === quote) { closed = true; break; }
      }
      if (!closed) throw new Error('Unclosed CSS string');
    }
  }
  return output;
}

export function generatedCSS(source) {
  const normalized = source.replace(/\r\n?/g, '\n');
  const hash = createHash('sha256').update(normalized).digest('hex');
  return `/* Generated by scripts/build-css.mjs; source SHA-256: ${hash} */\n${minifyCSS(normalized)}\n`;
}

export async function cssOutputs(siteRoot = root) {
  const directory = path.join(siteRoot, 'assets/css');
  const names = (await readdir(directory)).filter(name => name.endsWith('.css') && !name.endsWith('.min.css')).sort();
  return Promise.all(names.map(async name => {
    const source = await readFile(path.join(directory, name), 'utf8');
    return { source: `assets/css/${name}`, target: `assets/css/${name.replace(/\.css$/, '.min.css')}`, contents: generatedCSS(source) };
  }));
}

export async function checkCSS(siteRoot = root) {
  const errors = [];
  for (const output of await cssOutputs(siteRoot)) {
    let actual;
    try { actual = await readFile(path.join(siteRoot, output.target), 'utf8'); } catch { /* Report missing output as stale. */ }
    if (actual?.replace(/\r\n?/g, '\n') !== output.contents) errors.push(`${output.target} is missing or stale; run node scripts/build-css.mjs`);
  }
  const html = await readFile(path.join(siteRoot, 'index.html'), 'utf8');
  const loaded = new Set();
  for (const [tag] of html.matchAll(/<link\b[^>]*>/gi)) {
    if (!/\brel=["']stylesheet["']/i.test(tag)) continue;
    const href = /\bhref=["']([^"']+)["']/i.exec(tag)?.[1];
    if (!href || /^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(href)) continue;
    loaded.add(href.split(/[?#]/)[0]);
  }
  const practice = /<meta name="aec-practice-css" content="([^"]+)">/.exec(html)?.[1].split(/[?#]/)[0];
  if (practice && loaded.has(practice)) errors.push(`${practice} must load only on method routes`);
  async function measure(names, label, rawLimit, gzipLimit) {
    const files = [];
    for (const name of names) {
      try {
        const css = await readFile(path.join(siteRoot, name));
        files.push({ name, raw: css.length, gzip: gzipSync(css).length });
      } catch { errors.push(`${label} stylesheet missing: ${name}`); }
    }
    const raw = files.reduce((sum, file) => sum + file.raw, 0);
    const gzip = files.reduce((sum, file) => sum + file.gzip, 0);
    if (raw >= rawLimit) errors.push(`${label} CSS exceeds the <${rawLimit.toLocaleString('en-US')}-byte raw budget: ${raw} bytes`);
    if (gzip >= gzipLimit) errors.push(`${label} CSS exceeds the <${gzipLimit.toLocaleString('en-US')}-byte gzip budget: ${gzip} bytes`);
    return { files, raw, gzip };
  }
  const base = await measure(loaded, 'Base', 60_000, 15_000);
  const methods = practice ? await measure(new Set([...loaded, practice]), 'Methods', 72_000, 18_000) : null;
  return { errors, ...base, methods };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const output of await cssOutputs()) {
    await writeFile(path.join(root, output.target), output.contents);
    console.log(`${output.target}: ${Buffer.byteLength(output.contents)} bytes`);
  }
}
